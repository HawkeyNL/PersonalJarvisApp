#!/usr/bin/env python3
"""Convert the Instrument colour tokens (OKLCH, desktop/src/tokens.css) to the
sRGB table in ios/Jarvis/Views/Instrument.swift.

Usage: python3 ios/scripts/instrument_tokens.py [--check]

Prints the colour statics and the `Token` enum; paste them over the generated
block in Instrument.swift. --check fails if Instrument.swift is out of date.

Stdlib only. OKLCH -> OKLab -> linear sRGB uses Björn Ottosson's published
matrices (https://bottosson.github.io/posts/oklab/), then the sRGB transfer
curve, rounded to 8 bits. Any out-of-gamut value is an error.
"""
import math
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CSS = os.path.join(ROOT, "desktop/src/tokens.css")
SWIFT = os.path.join(ROOT, "ios/Jarvis/Views/Instrument.swift")
TOKEN = re.compile(r"--([a-z-]+):\s*oklch\(([\d.]+)\s+([\d.]+)\s+([\d.]+)(?:\s*/\s*([\d.]+))?\)\s*;")


def rule(css, selector):
    start = css.index(selector + " {")
    return css[start:css.index("}", start)]


def oklch_to_srgb(l, c, h):
    a, b = c * math.cos(math.radians(h)), c * math.sin(math.radians(h))
    l_ = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m_ = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s_ = (l - 0.0894841775 * a - 1.2914855480 * b) ** 3
    linear = (
        4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
        -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
        -0.0041960863 * l_ - 0.7034186147 * m_ + 1.7076147010 * s_,
    )
    out = []
    for v in linear:
        if v < -1e-4 or v > 1 + 1e-4:
            raise SystemExit(f"oklch({l} {c} {h}) is outside sRGB")
        v = min(max(v, 0.0), 1.0)
        v = 12.92 * v if v <= 0.0031308 else 1.055 * v ** (1 / 2.4) - 0.055
        out.append(round(v * 255))
    return out


def tokens(text):
    result = {}
    for name, l, c, h, alpha in TOKEN.findall(text):
        r, g, b = oklch_to_srgb(float(l), float(c), float(h))
        result[name] = (r << 24) | (g << 16) | (b << 8) | round(float(alpha or 1) * 255)
    return result


def camel(name):
    head, *rest = name.split("-")
    return head + "".join(part.capitalize() for part in rest)


def generate():
    css = open(CSS, encoding="utf-8").read()
    light, dark = tokens(rule(css, ":root")), tokens(rule(css, ':root[data-theme="dark"]'))
    if light.keys() != dark.keys():
        raise SystemExit(f"light/dark mismatch: {sorted(light.keys() ^ dark.keys())}")
    out = ["    // Generated by ios/scripts/instrument_tokens.py from desktop/src/tokens.css."]
    out += [f"    static let {camel(n)} = Color(Token.{camel(n)})" for n in light]
    out += ["", "    enum Token: String, CaseIterable {"]
    out += [f'        case {camel(n)} = "{n}"' for n in light]
    out += ["", "        /// sRGB 0xRRGGBBAA in light and dark.",
            "        var rgba: (light: UInt32, dark: UInt32) {", "            switch self {"]
    out += [f"            case .{camel(n)}: (0x{light[n]:08X}, 0x{dark[n]:08X})" for n in light]
    out += ["            }", "        }", "    }"]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    generated = generate()
    if sys.argv[1:] == ["--check"]:
        if generated not in open(SWIFT, encoding="utf-8").read():
            raise SystemExit("Instrument.swift is out of date: run ios/scripts/instrument_tokens.py")
        print("Instrument.swift matches desktop/src/tokens.css")
    else:
        sys.stdout.write(generated)
